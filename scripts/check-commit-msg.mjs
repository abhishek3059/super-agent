#!/usr/bin/env node
/**
 * commit-msg hook: enforce Conventional Commits for human and AI agents.
 * Allowed: feat, fix, docs, chore, refactor, test, build, ci, perf, style, revert.
 */
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("check-commit-msg: missing commit-message file argument");
  process.exit(1);
}

const raw = readFileSync(file, "utf8");
const lines = raw
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line.length > 0 && !line.startsWith("#"));

if (lines.length === 0) {
  console.error("check-commit-msg: empty commit message");
  process.exit(1);
}

const subject = lines[0];

// Merge and revert commits are generated by Git and are allowed through.
if (/^Merge /i.test(subject) || /^Revert "/i.test(subject)) {
  process.exit(0);
}

const pattern =
  /^(feat|fix|docs|chore|refactor|test|build|ci|perf|style|revert)(\([a-z0-9._-]+\))?!?: .{3,72}$/;

if (!pattern.test(subject)) {
  console.error(
    [
      "check-commit-msg: invalid commit subject.",
      "",
      "Use Conventional Commits: <type>(<scope>): <summary>",
      "Types: feat, fix, docs, chore, refactor, test, build, ci, perf, style, revert",
      "Summary: 3-72 characters.",
      "",
      `Received: ${subject}`,
      "",
      "Example: docs(prd): clarify RT-G00 runtime consent gate",
    ].join("\n"),
  );
  process.exit(1);
}
